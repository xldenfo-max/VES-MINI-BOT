cmd({
    pattern: "add",
    alias: ["a", "invite"],
    desc: "Adds a member to the group",
    category: "admin",
    react: "➕",
    filename: __filename
},
async (conn, mek, m, {
    from, q, isGroup, isBotAdmins, reply, quoted, senderNumber
}) => {
    // Check if the command is used in a group
    if (!isGroup) return reply("❌ This command can only be used in groups.");

    // Get the bot owner's number dynamically from conn.user.id
    const botOwner = conn.user.id.split(":")[0];
    if (senderNumber !== botOwner) {
        return reply("❌ Only the bot owner can use this command.");
    }

    // Check if the bot is an admin
    if (!isBotAdmins) return reply("❌ I need to be an admin to use this command.");

    let number;
    if (m.quoted) {
        number = m.quoted.sender.split("@")[0]; // If replying to a message, get the sender's number
    } else if (q && q.includes("@")) {
        number = q.replace(/[@\s]/g, ''); // If manually typing a number with '@'
    } else if (q && /^\d+$/.test(q)) {
        number = q; // If directly typing a number
    } else {
        return reply("❌ Please reply to a message, mention a user, or provide a number to add.");
    }

    const jid = number + "@s.whatsapp.net";

    try {
        await conn.groupParticipantsUpdate(from, [jid], "add");
        reply(`✅ Successfully added @${number}`, { mentions: [jid] });
    } catch (error) {
        console.error("Add command error:", error);
        reply("❌ Failed to add the member.");
    }
});

Cmd({
  pattern: "kick",
  alias: ["k", "💀"],
  desc: "Removes a participant by replying to or mentioning their message.",
  react: "🚪",
  category: "group",
  filename: __filename,
}, async (conn, mek, m, {
    from,
    quoted,
    isGroup,
    isAdmins,
    isOwner,
    isBotAdmins,
    reply
}) => {
    try {
        // Check if the command is used in a group
        if (!isGroup) return reply("❌ This command can only be used in groups.");
        
        // Only admins or the owner can use this command
        if (!isAdmins && !isOwner) return reply("❌ Only group admins or the owner can use this command.");
        
        // Check if the bot has admin privileges
        if (!isBotAdmins) return reply("❌ I need to be an admin to kick members.");
        
        // Determine the target user safely using reply or mention
        let target = quoted ? quoted.sender : (m.mentionedJid && m.mentionedJid[0]) ? m.mentionedJid[0] : null;

        if (!target && m.msg?.contextInfo?.mentionedJid?.length > 0) {
            target = m.msg.contextInfo.mentionedJid[0];
        }
        
        if (!target) {
            return reply("❌ Please mention or reply to the message of the participant to remove.");
        }
        
        // Remove the participant from the group
        await conn.groupParticipantsUpdate(from, [target], "remove");
        
        const tag = target.split('@')[0];
        return reply(`*@${tag} kicked successfully!* 👋`, { mentions: [target] });

    } catch (error) {
        console.error('Error while executing kick:', error);
        return reply(`❌ Failed to remove the participant: ${error.message || error}`);
    }
});

